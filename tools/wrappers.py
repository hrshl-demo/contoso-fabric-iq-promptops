"""Generate the thin wrappers that make each canonical prompt usable from every Copilot surface.

  .github/prompts/<id>.prompt.md          VS Code prompt files (slash command)
  .github/skills/<id-with-dashes>/SKILL.md   Copilot CLI / GitHub skills

The canonical text stays in prompts/; wrappers only point at it, so they cannot drift.
  python -m tools.wrappers --write    regenerate
  python -m tools.wrappers --check    fail if a wrapper is missing, stale or orphaned
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Optional

from .promptlib import ROOT, Prompt, load_prompts

MARKER = "generated by tools/wrappers.py"


def skill_name(p: Prompt) -> str:
    return p.id.replace(".", "-")


def vscode_wrapper(p: Prompt) -> str:
    desc = f"{p.meta['title']} ({p.id} {p.version})"
    return (
        "---\n"
        f"description: {json.dumps(desc)}\n"
        "agent: agent\n"
        "---\n"
        f"<!-- {MARKER} from {p.path}; do not edit -->\n"
        f"Run the canonical prompt [{p.path}](../../{p.path}) (`{p.id}` {p.version}) exactly as written, "
        "and follow [AGENTS.md](../../AGENTS.md). Ask me for any input value listed in its frontmatter before you start.\n"
    )


def skill_wrapper(p: Prompt) -> str:
    desc = f"{p.meta['title']} (prompt {p.id} {p.version}). Use when asked to run the {p.id} prompt. It opens a pull request and never deploys."
    return (
        "---\n"
        f"name: {skill_name(p)}\n"
        f"description: {json.dumps(desc)}\n"
        "---\n"
        f"<!-- {MARKER} from {p.path}; do not edit -->\n"
        f"Follow the canonical prompt in `{p.path}` exactly (id `{p.id}`, version {p.version}) and the rules in `AGENTS.md`. "
        "Ask for any input value listed in the prompt's frontmatter before you start.\n"
    )


def expected(root: Path = ROOT) -> dict[str, str]:
    prompts, _ = load_prompts(root)
    files: dict[str, str] = {}
    for p in prompts:
        if not p.id:
            continue
        files[f".github/prompts/{p.id}.prompt.md"] = vscode_wrapper(p)
        files[f".github/skills/{skill_name(p)}/SKILL.md"] = skill_wrapper(p)
    return files


def _generated_on_disk(root: Path) -> set[str]:
    found: set[str] = set()
    for pattern in (".github/prompts/*.prompt.md", ".github/skills/*/SKILL.md"):
        for f in root.glob(pattern):
            if MARKER in f.read_text(encoding="utf-8"):
                found.add(f.relative_to(root).as_posix())
    return found


def write(root: Path = ROOT) -> int:
    want = expected(root)
    for rel, text in want.items():
        target = root / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8", newline="\n")
    for rel in _generated_on_disk(root) - set(want):
        (root / rel).unlink()
        print(f"removed orphan wrapper {rel}")
    print(f"wrappers: wrote {len(want)} file(s)")
    return 0


def check(root: Path = ROOT) -> int:
    want = expected(root)
    problems = []
    for rel, text in want.items():
        f = root / rel
        if not f.exists():
            problems.append(f"{rel}: missing")
        elif f.read_text(encoding="utf-8").replace("\r\n", "\n") != text:
            problems.append(f"{rel}: stale")
    for rel in sorted(_generated_on_disk(root) - set(want)):
        problems.append(f"{rel}: orphan (its prompt is gone)")
    for line in problems:
        print(line)
    print(f"wrappers: {len(problems)} problem(s)" + ("; run python -m tools.wrappers --write" if problems else ""))
    return 1 if problems else 0


def main(argv: Optional[list[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--write", action="store_true")
    g.add_argument("--check", action="store_true")
    ap.add_argument("--root", default=str(ROOT))
    a = ap.parse_args(argv)
    root = Path(a.root)
    return write(root) if a.write else check(root)


if __name__ == "__main__":
    sys.exit(main())
